@dataclass(frozen=True)
class ExportEnv:
    ldraw: Path
    custom: Path
    tokens: dict
    config_dir: Path
    workers: int = min(8, os.cpu_count() or 1)

    @property
    def library(self) -> Library:
        return Library(self.ldraw, self.custom)

    def color(self, name: str) -> str:
        return next(t["value"] for t in self.tokens["color"]["tokens"] if t["name"] == name)


def write_assets(dest: Path, tokens: dict) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    css = (ASSETS / "components.css").read_text(encoding="utf-8")
    header = "/* Generated by lc from design/brick-steps.tokens.json; edit the Brick Steps artifact instead. */\n"
    (dest / "site.css").write_text(header + tokens_css(tokens) + css, encoding="utf-8")
    for name in ("manual.js", "viewer3d.js"):
        shutil.copyfile(ASSETS / name, dest / name)
    shutil.copytree(ASSETS / "vendor", dest / "vendor", dirs_exist_ok=True)


def _safe(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]", "_", name)


def _render_thumbs(keys: set[tuple[str, int]], thumbs_dir: Path, env: ExportEnv) -> dict[tuple[str, int], Path]:
    thumbs_dir.mkdir(parents=True, exist_ok=True)
    library = env.library

    def one(key: tuple[str, int]) -> tuple[tuple[str, int], Path]:
        part, color = key
        out = thumbs_dir / f"{_safe(part)}-{color}.png"
        if not out.exists():
            text = f"0 FILE thumb.ldr\n1 {color} 0 0 0 1 0 0 0 1 0 0 0 1 {part}.dat\n"
            mpd = thumbs_dir / f".{out.stem}.mpd"
            mpd.write_text(build_mpd(text, parse(text), library, env.custom), encoding="utf-8")
            render_image(mpd, out, env.ldraw, env.config_dir / out.stem, width=THUMB_SIZE, height=THUMB_SIZE,
                         background=env.color("paper"))
            mpd.unlink()
        return key, out

    with ThreadPoolExecutor(max_workers=env.workers) as pool:
        return dict(pool.map(one, sorted(keys)))


def load_mission_views(model_dir: Path) -> list[MissionView]:
    """Mission cards from models/<slug>/missions.yaml; `lc validate` reports problems in it."""
    path = model_dir / "missions.yaml"
    if not path.exists():
        return []
    missions, _ = parse_missions(yaml.safe_load(path.read_text(encoding="utf-8")) or [])
    return [MissionView(m.title, m.goal, blocks_html(m.blocks), m.try_) for m in missions]


def build_manual(name: str, slug: str, mpd_text: str, env: ExportEnv, out_dir: Path, *, thumbs_dir: Path,
                 thumbs_href: str, assets_href: str, sw_href: str | None, manifest_href: str | None,
                 pdf: bool, intro: str | None = None, missions: list[MissionView] | None = None) -> GalleryCard:
    """Render and write one manual into out_dir (index.html, img/, optional manual.pdf)."""
    doc = parse(mpd_text, default_name=f"{slug}.ldr")
    sections = plan(doc)
    out_dir.mkdir(parents=True, exist_ok=True)
    build = out_dir / "build.mpd"
    build.write_text(build_mpd(mpd_text, doc, env.library, env.custom), encoding="utf-8")

    section_images: list[dict[int, Path]] = []
    for k, section in enumerate(sections):
        count = len(step_groups(doc.models[section.submodel]))
        section_images.append(render_steps(
            build, out_dir / "img" / f"s{k}-.png", env.ldraw, env.config_dir / f"{slug}-s{k}",
            submodel=section.submodel, count=count, width=STEP_SIZE[0], height=STEP_SIZE[1],
            background=env.color("paper"), highlight=env.color("yellow"),
        ))

    thumbs = _render_thumbs(
        {(i.part, i.color) for s in sections for st in s.steps for i in st.items if not i.is_submodel}, thumbs_dir, env
    )
    final_of = {s.submodel: section_images[k][max(section_images[k])] for k, s in enumerate(sections) if section_images[k]}
    title_of = {s.submodel: s.title for s in sections}

    def rel(p: Path) -> str:
        return p.relative_to(out_dir).as_posix()

    steps: list[StepView] = []
    main = doc.main.name
    for k, section in enumerate(sections):
        shown = 0
        for st in section.steps:
            fresh = sum(i.qty for i in st.items)
            shown += fresh
            tray = [
                TrayItem(rel(final_of[i.part]), i.qty, title_of.get(i.part, i.part), is_submodel=True)
                if i.is_submodel else TrayItem(thumbs_href + thumbs[(i.part, i.color)].name, i.qty, i.part)
                for i in st.items
            ]
            steps.append(StepView(len(steps) + 1, rel(section_images[k][st.number]), tray,
                                  None if section.submodel == main else section.title,
                                  sub=section.submodel, shown=shown, fresh=fresh))

    hero = out_dir / "img" / "hero.png"
    shutil.copyfile(final_of[main], hero)
    (out_dir / MODEL_3D).write_text(pack_model(mpd_text, main, [env.ldraw, env.custom]), encoding="utf-8")
    view = ManualView(slug, name, sum(flatten(doc).values()), rel(hero), steps, "manual.pdf" if pdf else None,
                      model3d=MODEL_3D, main_sub=main, done_shown=len(doc.main.refs), intro=intro,
                      missions=missions or [])
    (out_dir / "index.html").write_text(
        manual_html(view, assets=assets_href, sw=sw_href, manifest=manifest_href), encoding="utf-8"
    )
    if pdf:
        from weasyprint import HTML  # imported lazily: needs Pango, only for export

        HTML(string=manual_html(view, assets=assets_href, print_mode=True), base_url=str(out_dir)).write_pdf(
            out_dir / "manual.pdf"
        )
    build.unlink()
    return GalleryCard(slug, name, f"{slug}/{rel(hero)}", view.part_count, len(steps))


def _brand(root: Path, out: Path) -> None:
    src = root / "design" / "brand"
    for dest, name in BRAND_FILES.items():
        (out / dest).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src / name, out / dest)


def build_site(root: Path, out: Path, env: ExportEnv, *, include_drafts: bool, pdf: bool) -> list[GalleryCard]:
    """Gallery + one manual per published model under out/, ready for GitHub Pages."""
    out.mkdir(parents=True, exist_ok=True)
    write_assets(out / "assets", env.tokens)
    shutil.copyfile(ASSETS / "sw.js", out / "sw.js")
    (out / "manifest.webmanifest").write_text(web_manifest(env.color("paper")), encoding="utf-8")
    (out / ".nojekyll").write_text("", encoding="utf-8")
    _brand(root, out)

    cards = []
    for meta_path in sorted((root / "models").glob("*/model.yaml")):
        meta = yaml.safe_load(meta_path.read_text(encoding="utf-8")) or {}
        if not is_published(meta, include_drafts):
            continue
        slug = meta_path.parent.name
        cards.append(build_manual(
            meta.get("name", slug), slug, (meta_path.parent / "model.mpd").read_text(encoding="utf-8"), env,
            out / slug, thumbs_dir=out / "parts", thumbs_href="../parts/", assets_href="../assets/",
            sw_href="../sw.js", manifest_href="../manifest.webmanifest", pdf=pdf,
            intro=(meta.get("story") or {}).get("intro"), missions=load_mission_views(meta_path.parent),
        ))
    (out / "index.html").write_text(gallery_html(cards), encoding="utf-8")
    return cards
