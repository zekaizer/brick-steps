"""Print the `track.ldr` block of models/tank-4/model.mpd: tread links closed around four wheels.

Usage: uv run python scripts/gen_tank_rhombus_track.py
The loop lies in the YZ plane at x = 0 and wraps the convex outline of WHEELS, each with the hinge
radius of sprocket 57519. Links are spread evenly, so their pitch is the perimeter over LINKS.
"""
import math

HINGE_RADIUS = 48.5  # hinge circle on sprocket 57519; the 36-tooth gears used as idlers are 47 in radius
# (y, z) wheel centres in loop order, top run first (towards +Z, as in gen_tank_track.py):
# horn idler, rear drive sprocket, road wheel, front idler.
WHEELS = [(-120.0, -60.0), (-80.0, 280.0), (0.0, 220.0), (0.0, 0.0)]
LINKS = 37  # perimeter 1101.2 LDU: 37 links of 30 leave 9 LDU of slack on fixed wheels
PER_STEP = 10


def _segments() -> list[tuple[str, tuple]]:
    """Straight runs and arcs of the loop, in order: ('line', (p0, p1)) and ('arc', (centre, a0, a1))."""
    n = len(WHEELS)
    out: list[tuple[str, tuple]] = []
    normals = []
    for i in range(n):
        (y0, z0), (y1, z1) = WHEELS[i], WHEELS[(i + 1) % n]
        dy, dz = y1 - y0, z1 - z0
        d = math.hypot(dy, dz)
        # Outward normal of the run from wheel i to i+1 (up on the top run).
        normals.append((-dz / d, dy / d))
    for i in range(n):
        c0, c1 = WHEELS[i], WHEELS[(i + 1) % n]
        ny, nz = normals[i]
        p0 = (c0[0] + HINGE_RADIUS * ny, c0[1] + HINGE_RADIUS * nz)
        p1 = (c1[0] + HINGE_RADIUS * ny, c1[1] + HINGE_RADIUS * nz)
        out.append(("line", (p0, p1)))
        a0 = math.atan2(nz, ny)
        my, mz = normals[(i + 1) % n]
        a1 = math.atan2(mz, my)
        while a1 > a0:
            a1 -= 2 * math.pi
        out.append(("arc", (c1, a0, a1)))
    return out


def _length(seg: tuple[str, tuple]) -> float:
    kind, v = seg
    if kind == "line":
        (y0, z0), (y1, z1) = v
        return math.hypot(y1 - y0, z1 - z0)
    return HINGE_RADIUS * (v[1] - v[2])


def point(s: float, segs: list[tuple[str, tuple]]) -> tuple[float, float]:
    for seg in segs:
        n = _length(seg)
        if s <= n:
            kind, v = seg
            if kind == "line":
                (y0, z0), (y1, z1) = v
                t = s / n if n else 0
                return y0 + (y1 - y0) * t, z0 + (z1 - z0) * t
            (cy, cz), a0, _ = v
            a = a0 - s / HINGE_RADIUS
            return cy + HINGE_RADIUS * math.cos(a), cz + HINGE_RADIUS * math.sin(a)
        s -= n
    raise ValueError(s)


def main() -> None:
    segs = _segments()
    perimeter = sum(_length(s) for s in segs)
    print("0 FILE track.ldr")
    print("0 사다리꼴 궤도")
    print("0 Name: track.ldr")
    print("0 Author: Brick Steps (generated by scripts/gen_tank_rhombus_track.py)")
    print(f"0 // {LINKS} links around a {perimeter:.1f} LDU loop, pitch {perimeter / LINKS:.2f}")
    print("0 !LC GROUND")
    for i in range(LINKS):
        y0, z0 = point(i * perimeter / LINKS, segs)
        y1, z1 = point(((i + 1) % LINKS) * perimeter / LINKS, segs)
        dy, dz = y1 - y0, z1 - z0
        n = math.hypot(dy, dz)
        dy, dz = dy / n, dz / n
        # Link 57518: hinge at its origin, body towards local -Z, tread face towards local -Y.
        # Local Z = -direction, local Y = inward normal, local X = Y x Z (stays on world X).
        zy, zz = -dy, -dz
        yy, yz = dz, -dy
        x = yy * zz - yz * zy
        print(f"1 0 0 {y0:.3f} {z0:.3f} {x:.5f} 0 0 0 {yy:.5f} {zy:.5f} 0 {yz:.5f} {zz:.5f} 57518.dat")
        if (i + 1) % PER_STEP == 0 and i + 1 < LINKS:
            print("0 STEP")
    print("0 STEP")
    print("0 NOFILE")


if __name__ == "__main__":
    main()
