"""Print the `track.ldr` block of models/tank-1/model.mpd: tread links closed around two sprockets.

Usage: uv run python scripts/gen_tank_track.py
The loop lies in the YZ plane at x = 0, around sprocket centers (y 0, z 0) and (y 0, z WHEELBASE).
"""
import math

WHEELBASE = 280.0  # LDU between the two sprocket axles
HINGE_RADIUS = 48.5  # hinge circle on sprocket 57519: 10 links of pitch 30 around it
LINKS = 29  # closest whole number of 30 LDU links for this loop
PER_STEP = 10


def point(s: float) -> tuple[float, float]:
    """(y, z) at arc length s, starting on top of the front sprocket and running backwards on top."""
    arc = math.pi * HINGE_RADIUS
    if s < WHEELBASE:
        return -HINGE_RADIUS, s
    s -= WHEELBASE
    if s < arc:
        a = s / HINGE_RADIUS
        return -HINGE_RADIUS * math.cos(a), WHEELBASE + HINGE_RADIUS * math.sin(a)
    s -= arc
    if s < WHEELBASE:
        return HINGE_RADIUS, WHEELBASE - s
    a = (s - WHEELBASE) / HINGE_RADIUS
    return HINGE_RADIUS * math.cos(a), -HINGE_RADIUS * math.sin(a)


def main() -> None:
    perimeter = 2 * WHEELBASE + 2 * math.pi * HINGE_RADIUS
    print("0 FILE track.ldr")
    print("0 궤도")
    print("0 Name: track.ldr")
    print("0 Author: Brick Steps (generated by scripts/gen_tank_track.py)")
    for i in range(LINKS):
        y0, z0 = point(i * perimeter / LINKS)
        y1, z1 = point(((i + 1) % LINKS) * perimeter / LINKS)
        dy, dz = y1 - y0, z1 - z0
        n = math.hypot(dy, dz)
        dy, dz = dy / n, dz / n
        # Link 57518: hinge at its origin, body towards local -Z, tread face towards local -Y.
        # Local Z = -direction, local Y = inward normal, local X = Y x Z (stays on world X).
        zy, zz = -dy, -dz
        yy, yz = dz, -dy
        x = yy * zz - yz * zy
        print(f"1 0 0 {y0:.3f} {z0:.3f} {x:.5f} 0 0 0 {yy:.5f} {zy:.5f} 0 {yz:.5f} {zz:.5f} 57518.dat")
        if (i + 1) % PER_STEP == 0 and i + 1 < LINKS:
            print("0 STEP")
    print("0 STEP")
    print("0 NOFILE")


if __name__ == "__main__":
    main()
