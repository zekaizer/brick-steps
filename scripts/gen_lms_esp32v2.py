"""Generate custom/parts/lms-esp32v2.dat, an approximate LDraw model of the LMS-ESP32 v2.0 board.

Measured: outline 39.8 x 55.8 mm (vendor), mounting holes on the Technic 5x7 frame (64179) corner
holes at (+-40, +-60) LDU (vendor photo of the board pinned to the frame).
Estimated from photos (+-3 mm): every component envelope below.
"""

from __future__ import annotations

from pathlib import Path

MM = 2.5  # LDU per mm
OUT = Path(__file__).resolve().parents[1] / "custom" / "parts" / "lms-esp32v2.dat"

BLACK, WHITE, SILVER, EDGE = 0, 15, 80, 24

HALF_X = 39.8 * MM / 2  # 49.75
HALF_Z = 55.8 * MM / 2  # 69.75
PCB_T = 1.6 * MM  # 4
TOP = -PCB_T  # PCB top face; -Y is up
HOLE_X, HOLE_Z, HOLE_R = 40.0, 60.0, 6.0


def f(v: float) -> str:
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return "0" if s == "-0" else s


def quad(c: int, *pts: tuple[float, float, float]) -> str:
    return f"4 {c} " + " ".join(f(v) for p in pts for v in p)


def line(a: tuple[float, float, float], b: tuple[float, float, float]) -> str:
    return f"2 {EDGE} " + " ".join(f(v) for v in (*a, *b))


def hface(c: int, y: float, x0: float, x1: float, z0: float, z1: float) -> str:
    return quad(c, (x0, y, z0), (x1, y, z0), (x1, y, z1), (x0, y, z1))


def box(c: int, x0: float, x1: float, y0: float, y1: float, z0: float, z1: float) -> list[str]:
    v = [(x, y, z) for x in (x0, x1) for y in (y0, y1) for z in (z0, z1)]
    faces = [(0, 1, 3, 2), (4, 6, 7, 5), (0, 4, 5, 1), (2, 3, 7, 6), (0, 2, 6, 4), (1, 5, 7, 3)]
    edges = [(0, 1), (2, 3), (4, 5), (6, 7), (0, 2), (1, 3), (4, 6), (5, 7), (0, 4), (1, 5), (2, 6), (3, 7)]
    return [quad(c, *(v[i] for i in fc)) for fc in faces] + [line(v[a], v[b]) for a, b in edges]


def sub(c: int, x: float, y: float, z: float, sx: float, sy: float, sz: float, name: str) -> str:
    return f"1 {c} {f(x)} {f(y)} {f(z)} {f(sx)} 0 0 0 {f(sy)} 0 0 0 {f(sz)} {name}"


def pcb() -> list[str]:
    lines: list[str] = []
    w, l, s = HALF_X, HALF_Z, HOLE_R
    hx0, hx1, hz0, hz1 = HOLE_X - s, HOLE_X + s, HOLE_Z - s, HOLE_Z + s
    for y in (TOP, 0.0):
        lines.append(hface(BLACK, y, -w, w, -hz0, hz0))
        for zs in (1, -1):
            za, zb = sorted((zs * hz0, zs * hz1))
            lines += [hface(BLACK, y, -w, -hx1, za, zb), hface(BLACK, y, -hx0, hx0, za, zb), hface(BLACK, y, hx1, w, za, zb)]
            zc, zd = sorted((zs * hz1, zs * l))
            lines.append(hface(BLACK, y, -w, w, zc, zd))
        for hx in (HOLE_X, -HOLE_X):
            for hz in (HOLE_Z, -HOLE_Z):
                lines.append(sub(BLACK, hx, y, hz, s, 1, s, "4-4ndis.dat"))
                lines.append(sub(EDGE, hx, y, hz, s, 1, s, "4-4edge.dat"))
    for hx in (HOLE_X, -HOLE_X):
        for hz in (HOLE_Z, -HOLE_Z):
            lines.append(sub(BLACK, hx, TOP, hz, s, PCB_T, s, "4-4cyli.dat"))
    # outer side walls and edges
    c = [(-w, -l), (w, -l), (w, l), (-w, l)]
    for (xa, za), (xb, zb) in zip(c, c[1:] + c[:1]):
        lines.append(quad(BLACK, (xa, TOP, za), (xb, TOP, zb), (xb, 0, zb), (xa, 0, za)))
        lines += [line((xa, TOP, za), (xb, TOP, zb)), line((xa, 0, za), (xb, 0, zb)), line((xa, TOP, za), (xa, 0, za))]
    return lines


def above(height_mm: float) -> tuple[float, float]:
    return TOP - height_mm * MM, TOP


def components() -> list[str]:
    lines: list[str] = []
    # LPUP ("HUB") socket on the -X long edge, inside the outline (does not overhang)
    lines += box(BLACK, -HALF_X + 1, -HALF_X + 26, *above(10), -45, -5)
    # ESP32 module (shield), -X long edge, +Z half
    lines += box(SILVER, -HALF_X + 1, 14, *above(3.1), 9, 54)
    # 2 x 14 pin header along the +X long edge, 2.54 mm pitch
    pitch = 2.54 * MM
    rows = (HALF_X - 3.5 * MM, HALF_X - 3.5 * MM - pitch)
    zspan = 7 * pitch
    lines += box(BLACK, rows[1] - pitch / 2, rows[0] + pitch / 2, *above(2.5), -zspan, zspan)
    for x in rows:
        for i in range(14):
            z = (i - 6.5) * pitch
            lines += box(SILVER, x - 0.8, x + 0.8, TOP - 8.5 * MM, TOP - 2.5 * MM, z - 0.8, z + 0.8)
    # USB-C on the +Z short edge
    lines += box(SILVER, 9, 31, *above(3.2), 52, HALF_Z)
    # Grove and Qwiic on the -Z short edge
    lines += box(WHITE, -7.5, 17.5, *above(7), -HALF_Z, -56)
    lines += box(WHITE, -27.5, -12.5, *above(3), -HALF_Z, -60)
    # 10-pin JST-SH display connector
    lines += box(WHITE, 12, 24, *above(3), -30, 2.5)
    return lines


HEADER = """\
0 LMS-ESP32 v2.0 Board (Approximate)
0 Name: lms-esp32v2.dat
0 Author: Brick Steps (generated by scripts/gen_lms_esp32v2.py)
0 !LDRAW_ORG Unofficial_Part
0 BFC NOCERTIFY
0 // Origin: PCB bottom center. PCB in the XZ plane, long side along Z, top face at y = -4.
0 // Mounting holes at (+-40, +-60) align with Technic 5x7 frame 64179 corner holes.
0 // Component boxes are clearance envelopes estimated from photos (+-3 mm). Rounded corners omitted.
"""


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEADER + "\n".join(pcb() + components()) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
